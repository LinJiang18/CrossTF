"""Solving the per-step fusion coefficients of one dataset.

Both stages minimise the hierarchical POT divergence (`pot.HierRef`) of the generated set,
averaged over training seeds x sampling seeds, subject to the energy distance not
exceeding its value at alpha = 1 (pure time branch) by more than k standard errors:

    min_a  J(a) = mean_{s, r} d_POT(G(a; s, r), X)
    s.t.   E(a) <= E(1) + k * SE[E(1)]

where G(a; s, r) is the set generated by the branches of training seed s from sampling
seed r. All evaluations share the same cached prefix and sampling seeds, so differences
between coefficient values are paired. SLSQP (scipy) drives both stages with
finite-difference gradients.

Stage 1 (`solve_single`): one coefficient shared by all six window steps, starting at
alpha = 1. The result is accepted only if its gain over alpha = 1 exceeds k times the
paired standard error of the gain; otherwise alpha = 1.

Stage 2 (`solve_capped`): one coefficient per window step, starting from the flat
schedule at the stage-1 value (before the acceptance test), with the additional
smoothness constraint sum_k (a_k - a_{k-1})^2 <= cap.

`solve` runs both stages and returns the stage-2 record, which is what
`main.py --sample --crosstf` uses.
"""

from __future__ import annotations

import time

import numpy as np
from scipy.optimize import minimize

from .evaluator import DEFAULT_WINDOW_SIGMA, Evaluator
from .pot import HierRef, energy_distance

DEFAULTS = dict(
    seeds=(4, 5, 6),            # training seeds whose branch pairs enter the objective
    sample_seeds=(101, 202),    # sampling seeds, shared by every evaluation
    window_sigma=DEFAULT_WINDOW_SIGMA,
    batch=128,                  # generation batch size inside the solve
    # stage 1
    eps=0.05,                   # finite-difference step
    maxiter=30,
    k_sigma=1.0,                # constraint slack and acceptance threshold, in SEs
    ftol=1e-4,                  # fallback SLSQP tolerance (only with a single draw)
    ftol_sem_div=2.0,           # SLSQP tolerance = SE(J(1)) / ftol_sem_div
    max_evals=45,               # hard cap on objective evaluations
    patience_evals=3,           # stop after this many gradients without improvement
    # stage 2
    cap=0.2,                    # smoothness cap on sum of squared step differences
    capped_eps=0.05,
    capped_k_sigma=1.0,
    capped_max_evals=135,
    capped_ftol_frac=1e-4,      # SLSQP tolerance as a fraction of J(1)
)


class Budget(Exception):
    """Raised by `Objective` to stop SLSQP (budget spent or no further progress)."""


class Objective:
    """J and E at a coefficient vector, cached so repeated probes cost nothing."""

    def __init__(self, ev, refs, seeds, ss_list, per_step, window, max_evals=None,
                 patience=None, patience_tol=0.0):
        self.ev, self.refs, self.seeds, self.ss = ev, refs, seeds, ss_list
        self.per_step, self.window = per_step, window
        self.cache, self.calls = {}, 0
        self.max_evals = max_evals
        self.patience, self.patience_tol = patience, patience_tol
        self.best_pot, self.calls_at_best = float('inf'), 0

    def _alphas(self, x):
        x = np.atleast_1d(x)
        return {i: float(x[k if self.per_step else 0]) for k, i in enumerate(self.window)}

    def __call__(self, x) -> dict:
        key = tuple(np.round(np.atleast_1d(x), 4))
        if key in self.cache:
            return self.cache[key]
        if self.max_evals is not None and self.calls >= self.max_evals:
            raise Budget(f'{self.calls} evaluations spent')
        pot, ener = [], []
        for sd in self.seeds:
            hier, real = self.refs[sd]
            for ss in self.ss:
                g = self.ev.generate(sd, self._alphas(x), ss)
                pot.append(hier.divergence(g))
                ener.append(energy_distance(g, real))
        # `per` keeps the value of every (training seed, sampling seed) draw, so that the
        # difference between two coefficient values can be treated as paired.
        pot = np.asarray(pot, dtype=float)
        ener = np.asarray(ener, dtype=float)
        out = {'pot': float(pot.mean()), 'energy': float(ener.mean()),
               'per': pot, 'ener_per': ener,
               'sem': float(pot.std(ddof=1) / np.sqrt(len(pot))) if len(pot) > 1 else 0.0,
               'ener_sem': float(ener.std(ddof=1) / np.sqrt(len(ener))) if len(ener) > 1 else 0.0}
        self.cache[key] = out
        self.calls += 1
        if out['pot'] < self.best_pot - self.patience_tol:
            self.best_pot, self.calls_at_best = out['pot'], self.calls
        if self.patience and self.calls - self.calls_at_best >= self.patience:
            raise Budget(f'no improvement above {self.patience_tol:.5f} in '
                         f'{self.patience} evaluations (best {self.best_pot:.4f} at '
                         f'call {self.calls_at_best})')
        print(f'    a={np.round(np.atleast_1d(x), 4).tolist()}  '
              f'pot {out["pot"]:.4f}  energy {out["energy"]:.4f}', flush=True)
        return out


def _roughness(x):
    """Sum of squared differences between consecutive steps; 0 for a flat schedule."""
    d = np.diff(np.atleast_1d(x))
    return float(np.dot(d, d))


def _roughness_grad(x):
    g = np.zeros_like(np.atleast_1d(x), dtype=float)
    d = np.diff(np.atleast_1d(x))
    g[:-1] -= 2.0 * d
    g[1:] += 2.0 * d
    return g


def best_feasible(obj, base, tol, x0):
    """Lowest-objective evaluated point satisfying the energy constraint."""
    feasible = [(v['pot'], k) for k, v in obj.cache.items()
                if v['energy'] <= base['energy'] + tol]
    best = min(feasible)[1] if feasible else tuple(np.atleast_1d(x0))
    return np.atleast_1d(np.asarray(best, dtype=float))


def _setup(config_file, name, device, log_root, cfg, sample_seeds):
    seeds = list(cfg['seeds'])
    ev = Evaluator(config_file, name, seeds, list(sample_seeds), cfg['batch'], device,
                   cfg['window_sigma'], log_root)
    ev.build_prefix(seeds)
    refs = {}
    for sd in seeds:
        real = ev.raw_real(sd)
        refs[sd] = (HierRef(real), real)
    return ev, refs, seeds


def solve_single(ev, refs, seeds, cfg, verbose=True):
    """Stage 1: one coefficient for the whole window."""
    t0 = time.time()
    window = ev.window
    n = 1
    obj = Objective(ev, refs, seeds, list(cfg['sample_seeds']), False, window,
                    max_evals=cfg['max_evals'],
                    patience=cfg['patience_evals'] * (n + 1) if cfg['patience_evals'] else None)
    x0 = np.ones(n)
    base = obj(x0)
    if verbose:
        print(f'  baseline a=1: pot {base["pot"]:.4f}  energy {base["energy"]:.4f}', flush=True)
    tol = cfg['k_sigma'] * base['ener_sem']
    ftol = base['sem'] / cfg['ftol_sem_div'] if base['sem'] > 0 else cfg['ftol']
    obj.patience_tol = ftol
    try:
        res = minimize(lambda x: obj(x)['pot'], x0, method='SLSQP',
                       bounds=[(0.0, 2.0)] * n,
                       constraints=[{'type': 'ineq',
                                     'fun': lambda x: base['energy'] + tol - obj(x)['energy']}],
                       options=dict(eps=cfg['eps'], maxiter=cfg['maxiter'], ftol=ftol))
        x, ok, msg = np.atleast_1d(res.x), bool(res.success), str(res.message)
    except Budget as e:
        x, ok = best_feasible(obj, base, tol, x0), False
        msg = f'stopped early ({e}); best feasible evaluated point returned'
    final = obj(x)
    if final['energy'] > base['energy'] + tol:
        x = best_feasible(obj, base, tol, x0)
        final = obj(x)
        ok = False
        msg = f'SLSQP returned an infeasible point; best feasible evaluated point returned ({msg})'

    # Accept only if the gain exceeds k paired standard errors.
    gain = base['pot'] - final['pot']
    d = base['per'] - final['per']
    noise_paired = float(d.std(ddof=1) / np.sqrt(len(d))) if len(d) > 1 else 0.0
    significant = gain > cfg['k_sigma'] * noise_paired
    fused = bool(np.any(np.abs(x - 1.0) > 1e-3)) and gain > 0 and significant
    alpha_raw = float(x[0])
    if not fused:
        x = np.ones_like(x)
        final = obj(x)
    return dict(alpha=float(x[0]), alpha_raw=alpha_raw, fused=fused,
                pot=final['pot'], pot_baseline=base['pot'], gain=float(gain),
                noise_paired=noise_paired, energy=final['energy'],
                energy_baseline=base['energy'], energy_tol=float(tol),
                k_sigma=cfg['k_sigma'], eps=cfg['eps'], success=ok, message=msg,
                evaluations=obj.calls, minutes=round((time.time() - t0) / 60, 2))


def solve_capped(ev, refs, seeds, cfg, a_single, verbose=True):
    """Stage 2: one coefficient per window step under the smoothness cap."""
    t0 = time.time()
    window = ev.window
    n = len(window)
    obj = Objective(ev, refs, seeds, list(cfg['sample_seeds']), True, window,
                    max_evals=cfg['capped_max_evals'],
                    patience=cfg['patience_evals'] * (n + 1) if cfg['patience_evals'] else None)
    base = obj(np.ones(n))
    tol = cfg['capped_k_sigma'] * base['ener_sem']
    ftol = cfg['capped_ftol_frac'] * base['pot']
    obj.patience_tol = 0.0
    x0 = np.full(n, a_single)          # flat start: roughness 0, inside the cap
    if verbose:
        print(f'  baseline pot {base["pot"]:.4f}  energy {base["energy"]:+.5f}  '
              f'cap {cfg["cap"]}  energy tol {tol:+.5f}  start a={a_single:.4f}', flush=True)
    pot_start = obj(x0)['pot']
    cap = cfg['cap']
    cons = [{'type': 'ineq', 'fun': lambda x: cap - _roughness(x),
             'jac': lambda x: -_roughness_grad(x)},
            {'type': 'ineq', 'fun': lambda x: base['energy'] + tol - obj(x)['energy']}]
    ok, msg = False, ''
    try:
        res = minimize(lambda x: obj(x)['pot'], x0, method='SLSQP',
                       bounds=[(0.0, 2.0)] * n, constraints=cons,
                       options=dict(eps=cfg['capped_eps'], maxiter=cfg['maxiter'], ftol=ftol))
        x, ok, msg = np.atleast_1d(res.x), bool(res.success), str(res.message)
    except Budget as e:
        x, msg = x0, f'stopped early ({e})'

    # The search may stop on a point outside its constraints; fall back to the best
    # feasible evaluated point.
    feasible = [(v['pot'], k) for k, v in obj.cache.items()
                if _roughness(np.asarray(k, dtype=float)) <= cap
                and v['energy'] <= base['energy'] + tol]
    if feasible:
        best_pot, key = min(feasible)
        r = obj(x) if ok else None
        if r is None or r['pot'] > best_pot or _roughness(x) > cap \
                or r['energy'] > base['energy'] + tol:
            x, ok = np.atleast_1d(np.asarray(key, dtype=float)), False
            msg = (msg + '; best feasible evaluated point returned').lstrip('; ')
    else:
        x, ok, msg = x0, False, 'no feasible point evaluated; flat start returned'
    r = obj(x)
    return dict(alpha=x.tolist(), roughness=_roughness(x), cap=cap,
                alpha_single=float(a_single), pot=r['pot'], pot_baseline=base['pot'],
                pot_flat_start=pot_start, gain=base['pot'] - r['pot'],
                energy=r['energy'], energy_baseline=base['energy'],
                energy_delta=r['energy'] - base['energy'], energy_tol=float(tol),
                constraint_ok=bool(r['energy'] <= base['energy'] + tol
                                   and _roughness(x) <= cap + 1e-9),
                k_sigma=cfg['capped_k_sigma'], eps=cfg['capped_eps'], ftol=ftol,
                success=ok, message=msg, evaluations=obj.calls,
                minutes=round((time.time() - t0) / 60, 2))


def solve(config_file, name, device='cuda', log_root=None, verbose=True, **over):
    """Both stages. Keyword arguments override `DEFAULTS` (e.g. from the config's
    `crosstf:` section). Returns the record written to alpha.json."""
    cfg = dict(DEFAULTS)
    cfg.update({k: v for k, v in over.items() if v is not None})
    ev, refs, seeds = _setup(config_file, name, device, log_root, cfg, cfg['sample_seeds'])
    if verbose:
        print(f'[{name}] stage 1: single coefficient', flush=True)
    single = solve_single(ev, refs, seeds, cfg, verbose)
    if verbose:
        print(f'[{name}] stage 1 alpha = {single["alpha_raw"]:.4f} '
              f'(accepted: {single["fused"]})\n[{name}] stage 2: per-step, cap {cfg["cap"]}',
              flush=True)
    capped = solve_capped(ev, refs, seeds, cfg, single['alpha_raw'], verbose)
    return dict(name=name, alpha=capped['alpha'], window_sigma=cfg['window_sigma'],
                window_steps=ev.window, seeds=seeds, sample_seeds=list(cfg['sample_seeds']),
                stage1=single, stage2=capped)
